def full_stats(**overrides: Any) -> UiStats:
    """Construct a UiStats with every contract field populated."""
    fields: dict[str, Any] = {
        "state": CaptureState.RUNNING,
        "frames_captured": 16_000,
        "chunks_emitted": 14,
        "chunks_dropped": 2,
        "overruns": 1,
        "xruns": 3,
        "peak_level": 0.7,
        "rms_level": 0.2,
        "display_peak": 0.8,
        "elapsed_s": 1.25,
        "latency_ms": 22.0,
    }
    fields.update(overrides)
    return UiStats(**fields)


def test_ui_stats_carries_every_contract_field() -> None:
    names = {f.name for f in dataclasses.fields(UiStats)}
    required = {
        "state",
        "frames_captured",
        "chunks_emitted",
        "chunks_dropped",
        "overruns",
        "xruns",
        "peak_level",
        "rms_level",
        "display_peak",
        "elapsed_s",
        "latency_ms",
        "message",
    }
    missing = required - names
    assert not missing, f"UiStats is missing contract fields: {sorted(missing)}"


def test_ui_stats_message_defaults_to_empty() -> None:
    assert full_stats().message == ""


def test_ui_stats_is_frozen() -> None:
    """The snapshot crosses into the widgets; nothing may edit it in place."""
    stats = full_stats()
    with pytest.raises((dataclasses.FrozenInstanceError, AttributeError)):
        stats.frames_captured = 99  # type: ignore[misc]
    assert stats.frames_captured == 16_000


