def test_peak_hold_starts_at_zero() -> None:
    hold = PeakHold(hold_s=1.0, decay_db_per_s=20.0)
    assert hold.value == pytest.approx(0.0)


def test_a_higher_level_is_taken_immediately() -> None:
    hold = PeakHold(hold_s=1.0, decay_db_per_s=20.0)

    assert hold.update(0.5, 0.0) == pytest.approx(0.5)
    assert hold.value == pytest.approx(0.5)
    assert hold.update(0.8, 0.1) == pytest.approx(0.8), (
        "a level above the current value must take it immediately -- the whole "
        "point of a peak meter"
    )
    assert hold.value == pytest.approx(0.8)


def test_update_returns_the_same_value_the_property_reports() -> None:
    hold = PeakHold(hold_s=1.0, decay_db_per_s=20.0)
    for i, level in enumerate([0.2, 0.9, 0.1, 0.4]):
        returned = hold.update(level, i * 0.05)
        assert returned == pytest.approx(hold.value), (
            "update() must return the value it just computed"
        )


def test_the_value_is_held_flat_for_hold_s() -> None:
    """StreamStats.peak_level is last-block-only; the hold is what makes it readable."""
    hold = PeakHold(hold_s=1.0, decay_db_per_s=20.0)
    hold.update(0.8, 0.0)

    now = 0.0
    while now < 0.95:
        now += 0.05
        value = hold.update(0.0, now)
        assert value == pytest.approx(0.8, abs=1e-6), (
            f"at t={now:.2f}s (hold_s=1.0) the value must still be the held "
            f"peak 0.8, got {value}"
        )


def test_a_new_peak_restarts_the_hold_window() -> None:
    hold = PeakHold(hold_s=1.0, decay_db_per_s=20.0)
    hold.update(0.4, 0.0)
    hold.update(0.9, 0.6)          # new peak at 0.6 -> hold now runs to 1.6

    assert hold.update(0.0, 1.5) == pytest.approx(0.9, abs=1e-6), (
        "the hold window must restart when a new peak is taken, otherwise a "
        "loud passage decays from when the meter first moved"
    )


def test_the_value_decays_at_roughly_decay_db_per_s_after_the_hold() -> None:
    """20 dB/s means a factor of 10 every second, once the hold has expired."""
    hold = PeakHold(hold_s=1.0, decay_db_per_s=20.0)
    hold.update(1.0, 0.0)

    now = 0.0
    while now < 1.5 - 1e-9:
        now = round(now + 0.05, 6)
        hold.update(0.0, now)
    half = hold.value
    assert 0.24 < half < 0.40, (
        f"0.5 s past a 1.0 s hold at 20 dB/s is -10 dB (~0.316), got {half}"
    )

    while now < 2.0 - 1e-9:
        now = round(now + 0.05, 6)
        hold.update(0.0, now)
    full = hold.value
    assert 0.06 < full < 0.15, (
        f"1.0 s past the hold at 20 dB/s is -20 dB (~0.100), got {full}"
    )
    assert full < half, "the decay must be monotonic while the input stays low"


def test_a_gentler_decay_rate_decays_more_slowly() -> None:
    fast = PeakHold(hold_s=0.5, decay_db_per_s=40.0)
    slow = PeakHold(hold_s=0.5, decay_db_per_s=10.0)
    for h in (fast, slow):
        h.update(1.0, 0.0)

    now = 0.0
    while now < 1.5 - 1e-9:
        now = round(now + 0.05, 6)
        fast.update(0.0, now)
        slow.update(0.0, now)

    assert fast.value < slow.value, (
        f"decay_db_per_s must actually govern the rate: 40 dB/s gave "
        f"{fast.value}, 10 dB/s gave {slow.value}"
    )


def test_the_value_never_goes_negative() -> None:
    hold = PeakHold(hold_s=0.1, decay_db_per_s=60.0)
    hold.update(1.0, 0.0)

    now = 0.0
    for _ in range(200):
        now = round(now + 0.5, 6)
        value = hold.update(0.0, now)
        assert value >= 0.0, f"a decaying peak must never go below 0.0, got {value}"
    assert hold.value < 1e-3, "after 100 s at 60 dB/s the meter must be at rest"


def test_a_negative_level_does_not_drive_the_value_negative() -> None:
    hold = PeakHold(hold_s=1.0, decay_db_per_s=20.0)
    assert hold.update(-0.5, 0.0) >= 0.0
    assert hold.value >= 0.0


def test_reset_clears_the_held_value() -> None:
    hold = PeakHold(hold_s=1.0, decay_db_per_s=20.0)
    hold.update(0.9, 0.0)
    assert hold.value == pytest.approx(0.9)

    hold.reset()
    assert hold.value == pytest.approx(0.0), "reset() must clear the held peak"

    assert hold.update(0.3, 100.0) == pytest.approx(0.3), (
        "after reset() the next level is taken immediately, whatever the clock"
    )


def test_peak_hold_never_reads_the_clock() -> None:
    """Identical `now` sequences must give identical values, however long the
    wall clock says the test took.  Reading time.monotonic() internally would
    make the meter untestable and its behaviour scheduler-dependent."""
    a = PeakHold(hold_s=1.0, decay_db_per_s=20.0)
    b = PeakHold(hold_s=1.0, decay_db_per_s=20.0)

    schedule = [(1.0, 0.0), (0.0, 0.5), (0.0, 1.4), (0.0, 2.2), (0.7, 2.3)]
    for level, now in schedule:
        a.update(level, now)
        time.sleep(0.02)           # real time passes only for `a`
        b.update(level, now)

    assert a.value == pytest.approx(b.value, rel=1e-9, abs=1e-12), (
        f"PeakHold must depend only on the supplied `now`: {a.value} != {b.value}"
    )


