def test_set_geometry_reconfigures_a_running_pipeline(
    replay: Callable[..., Any]
) -> None:
    """window_ms/hop_ms live in a frozen dataclass swapped atomically; no
    restart of the audio device is needed."""
    controller, _cfg, _n = replay(window_ms=100, hop_ms=50, realtime=True, loop=True)
    assert controller.start() is True
    pipeline = controller.pipeline
    assert pipeline is not None
    assert wait_until(lambda: controller.poll().chunks_emitted > 0), (
        f"the stream never got going; error={pipeline.error!r}"
    )

    assert controller.set_geometry(200, 50) is True

    assert controller.config.window_ms == 200
    assert pipeline.config.window_ms == 200, (
        "a running pipeline must be reconfigured, not merely remembered"
    )
    assert pipeline.config.hop_ms == 50
    assert controller.state is CaptureState.RUNNING, (
        "reconfiguring is not a restart"
    )
    assert pipeline.error is None
    assert controller.stop() is True


@pytest.mark.parametrize(
    ("window_ms", "hop_ms"),
    [
        (100, 200),        # hop > window: this pipeline is for overlapping windows
        (50, 500),
    ],
)
def test_a_hop_larger_than_the_window_is_rejected(
    window_ms: int,
    hop_ms: int,
    make_controller: Callable[..., CaptureController],
) -> None:
    original = make_config(window_ms=100, hop_ms=50)
    controller = make_controller(config=original)
    errors: list[str] = []
    controller.error_occurred.connect(errors.append)

    result = controller.set_geometry(window_ms, hop_ms)   # must not raise

    assert result is False
    assert errors, "the user must be told why the geometry was refused"
    assert isinstance(errors[0], str) and errors[0].strip()
    assert controller.config.window_ms == 100, "config must be left untouched"
    assert controller.config.hop_ms == 50
    assert controller.config == original


def test_a_sub_frame_geometry_is_rejected(
    make_controller: Callable[..., CaptureController]
) -> None:
    """A window that rounds to zero frames would emit empty chunks and make
    overlap_ratio divide by zero; window_ms > 0 alone does not catch it."""
    original = make_config(window_ms=100, hop_ms=100, sample_rate=100)
    assert original.window_frames == 10, "test setup: 1 ms == 0.1 frames here"
    controller = make_controller(config=original)
    errors: list[str] = []
    controller.error_occurred.connect(errors.append)

    result = controller.set_geometry(5, 5)   # 0.5 frames -> rounds to 0

    assert result is False, "a sub-frame window must be refused"
    assert errors
    assert controller.config == original, (
        f"a rejected geometry must leave config unchanged, got {controller.config}"
    )


def test_a_rejected_geometry_does_not_disturb_a_running_stream(
    replay: Callable[..., Any]
) -> None:
    controller, cfg, _n = replay(window_ms=100, hop_ms=50, realtime=True, loop=True)
    assert controller.start() is True
    assert wait_until(lambda: controller.poll().chunks_emitted > 0)

    assert controller.set_geometry(100, 400) is False

    assert controller.config == cfg, "config must survive a rejected change"
    assert controller.state is CaptureState.RUNNING, (
        "a validation failure is a user error, not a capture failure"
    )
    before = controller.poll().chunks_emitted
    assert wait_until(lambda: controller.poll().chunks_emitted > before), (
        "the stream must keep producing after a rejected reconfigure"
    )
    assert controller.stop() is True


