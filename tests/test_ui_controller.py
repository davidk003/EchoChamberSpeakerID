def ramp_int16(n: int) -> np.ndarray:
    """A distinct, strictly increasing int16 ramp -- off-by-ones are visible."""
    step = max(1, 60_000 // max(n, 1))
    idx = np.arange(n, dtype=np.int64)
    return ((idx * step) % 60_000 - 30_000).astype(np.int64)


def write_wav(path: Any, data: np.ndarray, sample_rate: int) -> Any:
    """Write a 16-bit PCM WAV; ``data`` is ``(n,)`` mono."""
    arr = np.asarray(data)
    if arr.ndim == 1:
        arr = arr.reshape(-1, 1)
    with wave.open(str(path), "wb") as w:
        w.setnchannels(arr.shape[1])
        w.setsampwidth(2)
        w.setframerate(sample_rate)
        w.writeframes(arr.astype("<i2").tobytes())
    return path


def n_windows(n_frames: int, w: int, h: int) -> int:
    """How many *full* windows fit in ``n_frames``; partial tails are dropped."""
    if n_frames < w:
        return 0
    return (n_frames - w) // h + 1


def make_config(
    window_ms: int = 100,
    hop_ms: int = 50,
    sample_rate: int = 1000,
    ring_seconds: float = 10.0,
    drop_policy: DropPolicy = DropPolicy.BLOCK,
) -> AudioConfig:
    """A config where 1 ms == 1 frame, so the geometry reads off the arguments."""
    return AudioConfig(
        sample_rate=sample_rate,
        window_ms=window_ms,
        hop_ms=hop_ms,
        ring_seconds=ring_seconds,
        drop_policy=drop_policy,
    )


def file_builder(
    path: Any,
    blocksize: int = 64,
    realtime: bool = False,
    loop: bool = False,
) -> Callable[..., Any]:
    """A ``source_factory_builder`` yielding a FileSource factory.

    The controller may call the builder with whatever it likes (the contract
    types it ``Callable[..., SourceFactory]``), so this swallows everything and
    returns the factory the pipeline expects: ``(on_audio, stats) -> source``.
    """
    def _builder(*args: Any, **kwargs: Any) -> Callable[..., FileSource]:
        def _factory(
            on_audio: Callable[[np.ndarray], None], stats: StreamStats
        ) -> FileSource:
            return FileSource(
                path,
                on_audio,
                blocksize=blocksize,
                realtime=realtime,
                loop=loop,
                stats=stats,
            )
        return _factory

    return _builder


def wait_until(pred: Callable[[], bool], timeout: float = TIMEOUT) -> bool:
    """Poll ``pred`` until it is true or ``timeout`` elapses (no event loop)."""
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if pred():
            return True
        time.sleep(0.005)
    return pred()


def chunk(seq: int, n: int = 100, value: float = 0.5) -> AudioChunk:
    """A plain AudioChunk for driving LatestChunkSink directly."""
    samples = np.full(n, value, dtype=np.float32)
    samples[0] = -1.0
    samples[-1] = 1.0
    return AudioChunk(
        samples=samples, start_frame=seq * n, seq=seq, sample_rate=1000
    )


def audio_threads() -> list[str]:
    """Names of pipeline threads currently alive."""
    interesting = {"file-source", "chunk-consumer"}
    return [
        t.name
        for t in threading.enumerate()
        if t.name in interesting or t.name.startswith("chunker")
    ]


