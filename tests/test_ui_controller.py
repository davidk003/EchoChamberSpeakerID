@pytest.fixture
def make_controller(qapp: Any) -> Iterator[Callable[..., CaptureController]]:
    """Factory registering every controller for guaranteed teardown.

    Teardown stops each controller, so a wedged replay, chunker or consumer
    thread cannot outlive the test that created it.
    """
    created: list[CaptureController] = []

    def _make(
        config: AudioConfig | None = None,
        builder: Callable[..., Any] | None = None,
        sd_module: Any | None = None,
    ) -> CaptureController:
        controller = CaptureController(
            config=config,
            source_factory_builder=builder,
            sd_module=FakeSounddevice() if sd_module is None else sd_module,
        )
        created.append(controller)
        return controller

    yield _make

    for controller in created:
        try:
            controller.stop()
        except Exception:  # pragma: no cover - teardown must not mask failures
            pass


@pytest.fixture
def replay(
    tmp_path: Any, make_controller: Callable[..., CaptureController]
) -> Callable[..., Any]:
    """Build a controller wired to a finite, as-fast-as-possible WAV replay."""
    def _replay(
        window_ms: int = 100,
        hop_ms: int = 50,
        n_frames: int = 1000,
        blocksize: int = 64,
        realtime: bool = False,
        loop: bool = False,
        ring_seconds: float = 10.0,
        drop_policy: DropPolicy = DropPolicy.BLOCK,
        sd_module: Any | None = None,
    ) -> tuple[CaptureController, AudioConfig, int]:
        cfg = make_config(
            window_ms=window_ms,
            hop_ms=hop_ms,
            ring_seconds=ring_seconds,
            drop_policy=drop_policy,
        )
        path = write_wav(
            tmp_path / f"replay_{window_ms}_{hop_ms}_{n_frames}.wav",
            ramp_int16(n_frames),
            cfg.sample_rate,
        )
        controller = make_controller(
            config=cfg,
            builder=file_builder(
                path, blocksize=blocksize, realtime=realtime, loop=loop
            ),
            sd_module=sd_module,
        )
        controller.refresh_devices()
        return controller, cfg, n_frames

    return _replay


