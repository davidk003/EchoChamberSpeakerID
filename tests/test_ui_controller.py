def test_poll_surfaces_a_dead_pipeline_as_error(
    tmp_path: Any, make_controller: Callable[..., CaptureController]
) -> None:
    """Background threads never re-raise; poll() is the GUI's only chance to
    notice that capture died."""
    cfg = make_config(window_ms=100, hop_ms=50, ring_seconds=1.0)
    assert cfg.ring_frames == 1000, "test setup: the ring must be 1000 frames"
    path = write_wav(tmp_path / "dead.wav", ramp_int16(4000), cfg.sample_rate)

    # Blocks larger than the ring make ring.write raise on the source thread.
    controller = make_controller(
        config=cfg, builder=file_builder(path, blocksize=1500)
    )
    controller.refresh_devices()
    errors: list[str] = []
    states: list[CaptureState] = []
    controller.error_occurred.connect(errors.append)
    controller.state_changed.connect(states.append)

    assert controller.start() is True
    pipeline = controller.pipeline
    assert pipeline is not None
    assert wait_until(lambda: pipeline.error is not None), (
        "test setup: the oversized block must kill the source thread"
    )

    stats = controller.poll()

    assert controller.state is CaptureState.ERROR, (
        "a pipeline whose error is set must move the controller to ERROR"
    )
    assert stats.state is CaptureState.ERROR
    assert CaptureState.ERROR in states
    assert errors, "error_occurred must describe the failure to the user"
    assert isinstance(errors[0], str) and errors[0].strip()
    assert controller.stop() is True


def test_a_dead_pipeline_stops_the_poll_timer(
    tmp_path: Any, make_controller: Callable[..., CaptureController], qtbot: Any
) -> None:
    """Once capture has died there is nothing left to poll; the timer must not
    keep burning event-loop time (and re-announcing) forever."""
    cfg = make_config(window_ms=100, hop_ms=50, ring_seconds=1.0)
    path = write_wav(tmp_path / "dead2.wav", ramp_int16(4000), cfg.sample_rate)
    controller = make_controller(
        config=cfg, builder=file_builder(path, blocksize=1500)
    )
    controller.refresh_devices()
    collected: list[UiStats] = []
    controller.stats_updated.connect(collected.append)

    assert controller.start() is True
    pipeline = controller.pipeline
    assert pipeline is not None
    assert wait_until(lambda: pipeline.error is not None)

    qtbot.waitUntil(lambda: controller.state is CaptureState.ERROR, timeout=TIMEOUT_MS)
    qtbot.wait(int(QUIET_S * 1000))
    settled = len(collected)
    qtbot.wait(int(QUIET_S * 1000))

    assert len(collected) == settled, (
        f"the poll timer must stop once the pipeline is dead; it emitted "
        f"{len(collected) - settled} more times over {QUIET_S}s"
    )
    assert controller.stop() is True


# --------------------------------------------------------------------------
# Poll timer configuration
#
# Both of these are stated architectural requirements that nothing asserted.
# With Qt's default CoarseTimer the 33 ms interval is rounded to the Windows
# scheduler tick and runs at ~21 Hz instead of 30 -- a third of the UI frames
# silently missing, with nothing to indicate why.
# --------------------------------------------------------------------------


def test_poll_timer_is_precise_not_coarse() -> None:
    from PySide6.QtCore import Qt

    from echochamber.ui.controller import CaptureController

    controller = CaptureController()
    try:
        assert controller.poll_timer.timerType() == Qt.TimerType.PreciseTimer, (
            "a CoarseTimer rounds the 33 ms poll to the Windows scheduler tick "
            "and delivers ~21 Hz instead of the specified 30 Hz"
        )
    finally:
        controller.stop()


def test_poll_interval_is_the_specified_30hz() -> None:
    from echochamber.ui.controller import POLL_INTERVAL_MS, CaptureController

    assert POLL_INTERVAL_MS == 33, "the architecture specifies ~30 Hz GUI updates"
    controller = CaptureController()
    try:
        assert controller.poll_timer.interval() == POLL_INTERVAL_MS
    finally:
        controller.stop()


