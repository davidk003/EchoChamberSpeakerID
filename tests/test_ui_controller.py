"""Tests for echochamber.ui.controller, written from the step-5 API contract.

Written from the *spec*, not the implementation.  Nothing here needs a
microphone: every controller is driven through the ``source_factory_builder``
seam with a :class:`FileSource` replaying a WAV generated by :mod:`wave` into
``tmp_path``, and device enumeration runs against ``tests.fake_sounddevice``.
That is the whole point of those two seams -- the deployment target (Windows
ARM64) and any CI box have neither this developer's microphone nor his device
table, and a test that needs either is a test that quietly stops running.

Determinism strategy, borrowed from ``test_pipeline.py``:

* ``sample_rate=1000`` so ``1 ms == 1 frame`` and every window/hop arithmetic
  assertion reads directly off the arguments;
* ``DropPolicy.BLOCK`` plus a ring far larger than the file, so the chunk count
  is exactly ``n_windows(n, W, H)`` and nothing can be dropped or overrun;
* every wait is event-driven with a multi-second bound;
* every controller is stopped in fixture teardown, so no audio thread can
  outlive its test.

The two Qt-specific rules the contract cares about are asserted directly:
:class:`LatestChunkSink` is not a ``QObject`` (it runs on the consumer thread),
and ``stats_updated`` only ever fires on the GUI thread.
"""

