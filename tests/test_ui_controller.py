def test_latest_chunk_sink_is_not_a_qobject() -> None:
    """The sink runs on the consumer thread; a QObject there is the bug the
    whole polling design exists to prevent."""
    assert not issubclass(LatestChunkSink, QObject), (
        "LatestChunkSink must not be a QObject: it is called from the audio "
        "consumer thread, which may never touch Qt"
    )
    sink = LatestChunkSink()
    assert not isinstance(sink, QObject)
    assert not hasattr(sink, "emit"), "a recording sink emits nothing"


def test_latest_chunk_sink_records_the_newest_seq() -> None:
    sink = LatestChunkSink(preview_points=64)
    for k in range(5):
        sink.on_chunk(chunk(k))

    seq, preview = sink.snapshot()
    assert seq == 4, f"snapshot() must report the newest chunk's seq, got {seq}"
    assert isinstance(preview, np.ndarray)
    assert preview.size > 0
    sink.close()


def test_latest_chunk_sink_snapshot_before_any_chunk_is_safe() -> None:
    sink = LatestChunkSink(preview_points=32)
    seq, preview = sink.snapshot()

    assert isinstance(seq, int)
    assert seq < 0, (
        f"with no chunk yet there is no sequence number to report; expected a "
        f"negative sentinel, got {seq}"
    )
    assert isinstance(preview, np.ndarray)
    sink.close()


def test_latest_chunk_sink_snapshot_returns_a_copy() -> None:
    """Mutating the returned preview must not corrupt what the GUI reads next."""
    sink = LatestChunkSink(preview_points=64)
    sink.on_chunk(chunk(0))

    _, first = sink.snapshot()
    before = first.copy()
    first += 42.0

    _, second = sink.snapshot()
    assert np.array_equal(second, before), (
        "snapshot() must return a copy; the caller scribbled on it and the "
        "next snapshot changed"
    )
    sink.close()


def test_latest_chunk_sink_does_not_alias_the_chunk_samples() -> None:
    sink = LatestChunkSink(preview_points=1024)
    c = chunk(0, n=256)
    sink.on_chunk(c)
    original = c.samples.copy()

    _, preview = sink.snapshot()
    preview[:] = 0.0

    assert np.array_equal(c.samples, original), (
        "the preview must not be a view into the chunk the pipeline still owns"
    )
    sink.close()


@pytest.mark.parametrize("preview_points", [8, 64, 512])
@pytest.mark.parametrize("n_samples", [16, 3000, 48_000])
def test_preview_is_decimated_to_at_most_preview_points(
    preview_points: int, n_samples: int
) -> None:
    """A 3 s window at 16 kHz is 48000 samples; the GUI cannot draw them all."""
    sink = LatestChunkSink(preview_points=preview_points)
    sink.on_chunk(chunk(0, n=n_samples))

    _, preview = sink.snapshot()
    assert preview.ndim == 1
    assert 0 < preview.size <= preview_points, (
        f"a {n_samples}-sample chunk must be decimated to at most "
        f"{preview_points} points, got {preview.size}"
    )
    sink.close()


def test_latest_chunk_sink_close_is_safe_and_idempotent() -> None:
    sink = LatestChunkSink()
    sink.on_chunk(chunk(0))
    sink.close()
    sink.close()


